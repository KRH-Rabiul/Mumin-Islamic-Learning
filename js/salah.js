// ---- Main render + animation ----
function render() {
  renderSidebar();
  const box = $('#lessonMain');
  const html =
    currentModule === 'wudu'
      ? renderWudu()
      : currentModule === 'prep'
        ? renderPrep()
        : currentModule === 'salah'
          ? renderSalah()
          : renderDua();
  box.innerHTML = `<div class="lesson-content page-enter">${html}</div>`;
  $$('[data-prev]', box).forEach(
    (button) =>
      (button.onclick = () => {
        currentIndex = Math.max(0, currentIndex - 1);
        render();
        animateLesson();
      })
  );
  $$('[data-next]', box).forEach(
    (button) =>
      (button.onclick = () => {
        currentIndex = Math.min(Number(button.dataset.total) - 1, currentIndex + 1);
        render();
        animateLesson();
      })
  );
}

function animateLesson() {
  const main = $('#lessonMain');
  if (!main) return;
  main.classList.remove('lesson-refresh');
  void main.offsetWidth;
  main.classList.add('lesson-refresh');
}

